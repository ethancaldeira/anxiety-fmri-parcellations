"""
Group Parcellation Pipeline – Train-Only
========================================
Builds STAI-t stratified group parcellations from the TRAIN subjects of a
split file (default data/gsp_split.json, generated by make_gsp_split.py),
keeping the test set held out for evaluation.

Inputs are read from, and outputs uploaded to, s3://<bucket>/GSP_Parcellation/;
the bucket is given with --bucket or the PARCELLATION_BUCKET environment
variable.

Usage:
    # Group-mean, tertile split, train subjects only (defaults)
    python run_group_parcellation_split.py \
        --participants /path/to/GSP_participants.tsv

    # Use test subjects instead (e.g. for comparison)
    python run_group_parcellation_split.py \
        --participants /path/to/GSP_participants.tsv \
        --use-set test
"""

import os
import re
import sys
import json
import argparse
import tempfile
import boto3
import pandas as pd
import nibabel as nib
import numpy as np

from src.group_binfile_parcellation import group_binfile_parcellate
from src.group_mean_binfile_parcellation import group_mean_binfile_parcellate

# ── Defaults ──────────────────────────────────────────────────────────────────
SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
DEFAULT_MASK_PATH = os.path.join(SCRIPT_DIR, "masks", "grey_matter_mask.nii.gz")
DEFAULT_SPLIT_PATH = os.path.join(SCRIPT_DIR, "data", "gsp_split.json")  # make_gsp_split.py
DEFAULT_BUCKET = os.environ.get("PARCELLATION_BUCKET")
DEFAULT_NUM_CLUSTERS = 200

S3_INDIVIDUAL_PREFIX = "GSP_Parcellation/individual"   # per-voxel labels from run_individual_parcellation.py
S3_CONNECTIVITY_PREFIX = "GSP_Parcellation/connectivity"
S3_GROUP_OUTPUT_PREFIX = "GSP_Parcellation/group_split"

DEFAULT_WORK_DIR = os.path.join(tempfile.gettempdir(), "parcellation_group_split_work")


def parse_args():
    parser = argparse.ArgumentParser(
        description="Run group parcellation using only train (or test) subjects from a split file"
    )
    parser.add_argument("--participants", type=str, required=True,
                        help="Path to the GSP participants TSV file (participant_id, "
                             "STAI_tAnxiety; Anxiety_Binary for --split binary)")
    parser.add_argument("--split-file", type=str, default=DEFAULT_SPLIT_PATH,
                        help="Path to the split JSON (default: data/gsp_split.json in this "
                             "repository, written by make_gsp_split.py)")
    parser.add_argument("--use-set", type=str, default="train",
                        choices=["train", "test"],
                        help="Which split set to use for building the group parcellation (default: train)")
    parser.add_argument("--mask", type=str, default=DEFAULT_MASK_PATH,
                        help="Path to grey matter mask NIfTI")
    parser.add_argument("--clusters", type=int, default=DEFAULT_NUM_CLUSTERS,
                        help=f"Number of clusters/parcels K (default: {DEFAULT_NUM_CLUSTERS})")
    parser.add_argument("--method", type=str, default="group-mean",
                        choices=["two-level", "group-mean"],
                        help="Group clustering method (default: group-mean)")
    parser.add_argument("--split", type=str, default="tertile",
                        choices=["median", "tertile", "binary", "custom"],
                        help="How to stratify subjects by STAI-t (default: tertile; 'binary' "
                             "uses the Anxiety_Binary column of the participants file)")
    parser.add_argument("--custom-threshold", type=float, nargs="+", default=None,
                        help="Custom STAI-t threshold(s). One value = binary, two = three groups.")
    parser.add_argument("--bucket", type=str, default=DEFAULT_BUCKET,
                        help="S3 bucket holding the individual results and the outputs "
                             "(default: $PARCELLATION_BUCKET)")
    parser.add_argument("--work-dir", type=str, default=DEFAULT_WORK_DIR,
                        help=f"Local scratch directory for downloads and the group parcellations "
                             f"(default: {DEFAULT_WORK_DIR})")
    parser.add_argument("--seed", type=int, default=None,
                        help="Seed for the random initialisation of the clustering, applied to "
                             "each group (default: unseeded)")
    parser.add_argument("--dry-run", action="store_true",
                        help="Show group assignments without running clustering")
    parser.add_argument("--no-upload", action="store_true",
                        help="Keep the group parcellations in --work-dir instead of uploading to S3")
    return parser.parse_args()


# ── Subject ID Conversion ────────────────────────────────────────────────────
def participant_to_bids(participant_id):
    match = re.match(r"Sub(\d+)_S\d+", participant_id)
    if not match:
        return None
    return f"sub-{match.group(1)}"


# ── Load the split file and filter participants ──────────────────────────────────
def load_split_subjects(split_path, use_set):
    """Load train or test subject IDs from the split file."""
    with open(split_path, "r") as f:
        split = json.load(f)

    if use_set not in split:
        raise ValueError(f"Key '{use_set}' not found in {split_path}. "
                         f"Available keys: {[k for k in split if isinstance(split[k], list)]}")

    subjects = split[use_set]
    n_train = len(split.get("train", []))
    n_val = len(split.get("val", []))
    n_test = len(split.get("test", []))
    print(f"Loaded {len(subjects)} {use_set} subjects from {split_path}")
    print(f"  (train: {n_train}, val: {n_val}, test: {n_test}, total: {n_train + n_val + n_test})")
    return set(subjects)


# ── Stage 1: Load Metadata & Stratify (train-only) ──────────────────────────
def load_and_stratify(participants_path, split_subjects, split_method, custom_thresholds):
    """Load participants, filter to split subjects with STAI-t scores, and assign groups."""
    df = pd.read_csv(participants_path, sep="\t", dtype={"participant_id": str})

    # Filter to only the split subjects
    df = df[df["participant_id"].isin(split_subjects)]
    n_matched = len(df)
    n_requested = len(split_subjects)
    if n_matched < n_requested:
        print(f"  WARNING: {n_requested - n_matched} split subjects not found in participants file")

    # Must have STAI-t scores
    df = df[df["STAI_tAnxiety"].notna()].copy()
    stai_scores = df["STAI_tAnxiety"].astype(float)

    print(f"\nSTAI-t score statistics (n={len(df)}):")
    print(f"  Mean: {stai_scores.mean():.1f}")
    print(f"  Std:  {stai_scores.std():.1f}")
    print(f"  Min:  {stai_scores.min():.1f}")
    print(f"  Max:  {stai_scores.max():.1f}")
    print(f"  Median: {stai_scores.median():.1f}")

    # Assign groups based on split method
    if split_method == "median":
        median_val = stai_scores.median()
        df["anxiety_group"] = np.where(stai_scores <= median_val, "low_anxiety", "high_anxiety")
        print(f"\nMedian split at STAI-t = {median_val:.1f}")

    elif split_method == "tertile":
        t1 = stai_scores.quantile(1/3)
        t2 = stai_scores.quantile(2/3)
        conditions = [
            stai_scores <= t1,
            (stai_scores > t1) & (stai_scores <= t2),
            stai_scores > t2,
        ]
        df["anxiety_group"] = np.select(conditions, ["low_anxiety", "mid_anxiety", "high_anxiety"], default="mid_anxiety")
        print(f"\nTertile split at STAI-t = {t1:.1f} and {t2:.1f}")

    elif split_method == "binary":
        if "Anxiety_Binary" not in df.columns:
            raise ValueError("Anxiety_Binary column not found in participants file")
        df["anxiety_group"] = np.where(df["Anxiety_Binary"] == 0, "low_anxiety", "high_anxiety")
        print("\nUsing Anxiety_Binary column (0 = low, 1 = high)")

    elif split_method == "custom":
        if not custom_thresholds:
            raise ValueError("--custom-threshold required when using --split custom")
        if len(custom_thresholds) == 1:
            thresh = custom_thresholds[0]
            df["anxiety_group"] = np.where(stai_scores <= thresh, "low_anxiety", "high_anxiety")
            print(f"\nCustom split at STAI-t = {thresh:.1f}")
        elif len(custom_thresholds) == 2:
            t1, t2 = sorted(custom_thresholds)
            conditions = [
                stai_scores <= t1,
                (stai_scores > t1) & (stai_scores <= t2),
                stai_scores > t2,
            ]
            df["anxiety_group"] = np.select(conditions, ["low_anxiety", "mid_anxiety", "high_anxiety"], default="mid_anxiety")
            print(f"\nCustom split at STAI-t = {t1:.1f} and {t2:.1f}")
        else:
            raise ValueError("--custom-threshold accepts 1 or 2 values")

    # Build metadata grouped by anxiety level
    groups = {}
    for group_name in df["anxiety_group"].unique():
        group_df = df[df["anxiety_group"] == group_name]
        entries = []
        for _, row in group_df.iterrows():
            pid = str(row["participant_id"])
            bids_id = participant_to_bids(pid)
            if bids_id:
                entries.append({
                    "participant_id": pid,
                    "bids_id": bids_id,
                    "stai_t": row["STAI_tAnxiety"],
                })
        groups[group_name] = entries
        stai_vals = [e["stai_t"] for e in entries]
        print(f"  {group_name}: {len(entries)} subjects "
              f"(STAI-t range: {min(stai_vals):.0f}-{max(stai_vals):.0f})")

    return groups


# ── Stage 2: Download Individual Results ─────────────────────────────────────
def download_individual_labels(entries, s3, bucket, num_clusters, work_dir):
    """Download individual parcellation label .npy files from S3. Returns list of local paths."""
    local_files = []
    failed = []

    for entry in entries:
        pid = entry["participant_id"]
        s3_key = f"{S3_INDIVIDUAL_PREFIX}/ROI_{num_clusters}/npy/{pid}.npy"
        local_path = os.path.join(work_dir, f"label_{pid}.npy")

        try:
            s3.download_file(bucket, s3_key, local_path)

            # Convert 0-based labels to 1-based (group_binfile_parcellate expects 1..K)
            labels = np.load(local_path)
            labels = labels + 1
            np.save(local_path, labels)

            local_files.append(local_path)
        except Exception as e:
            print(f"  Could not download labels for {pid}: {e}")
            failed.append(pid)

    if failed:
        print(f"  WARNING: {len(failed)} subjects missing individual parcellations")

    return local_files


def download_connectivity_matrices(entries, s3, bucket, num_clusters, work_dir):
    """Download connectivity matrices from S3. Returns list of local paths."""
    local_files = []
    failed = []

    for entry in entries:
        pid = entry["participant_id"]
        s3_key = f"{S3_CONNECTIVITY_PREFIX}/ROI_{num_clusters}/{pid}.npy"
        local_path = os.path.join(work_dir, f"conn_{pid}.npy")

        try:
            s3.download_file(bucket, s3_key, local_path)
            local_files.append(local_path)
        except Exception as e:
            print(f"  Could not download connectivity for {pid}: {e}")
            failed.append(pid)

    if failed:
        print(f"  WARNING: {len(failed)} subjects missing connectivity matrices")
        if len(failed) == len(entries):
            print("  HINT: Run individual parcellation with --save-connectivity first")

    return local_files


# ── Stage 3: Run Group Clustering ────────────────────────────────────────────
def get_n_voxels(mask_path):
    """Get number of in-mask voxels."""
    msk = nib.load(mask_path)
    return int(np.count_nonzero(msk.get_fdata()))


def run_two_level(local_label_files, group_name, num_clusters, n_voxels, work_dir, seed=None):
    outfile = os.path.join(work_dir, f"group_{group_name}_{num_clusters}.npy")
    print(f"  Running 2-level clustering (K={num_clusters}, n_subjects={len(local_label_files)})")
    group_img = group_binfile_parcellate(local_label_files, outfile, num_clusters, n_voxels,
                                         seed=seed)
    return outfile, group_img


def run_group_mean(local_conn_files, group_name, num_clusters, n_voxels, work_dir, seed=None):
    outprefix = os.path.join(work_dir, f"group_mean_{group_name}")
    print(f"  Running group-mean clustering (K={num_clusters}, n_subjects={len(local_conn_files)})")
    group_mean_binfile_parcellate(local_conn_files, outprefix, [num_clusters], n_voxels,
                                  seed=seed)
    outfile = f"{outprefix}_{num_clusters}.npy"
    group_img = np.load(outfile, allow_pickle=True)
    return outfile, group_img


# ── Stage 4: Save & Upload ───────────────────────────────────────────────────
def save_and_upload(group_img, outfile, group_name, method, num_clusters, mask_path, bucket, s3, use_set,
                    work_dir, upload=True):
    """Save group parcellation as NIfTI and upload to S3."""
    mask_img = nib.load(mask_path)
    mask_data = mask_img.get_fdata().astype(bool)
    affine = mask_img.affine

    # Map labels back into 3D volume
    label_volume = np.zeros(mask_data.shape, dtype=np.uint16)
    flat_labels = np.asarray(group_img).flatten().astype(np.uint16)
    label_volume[mask_data] = flat_labels

    # Save locally
    local_nifti = os.path.join(work_dir, f"group_{group_name}_{method}_{num_clusters}_{use_set}.nii.gz")
    nib.save(nib.Nifti1Image(label_volume, affine), local_nifti)
    print(f"  Saved NIfTI: {local_nifti}")
    print(f"  Unique labels: {len(np.unique(flat_labels))}, shape: {label_volume.shape}")

    if not upload:
        return

    # Upload to S3 under group_split/<set>/ prefix
    s3_key = (f"{S3_GROUP_OUTPUT_PREFIX}/{use_set}/{group_name}/{method}"
              f"/ROI_{num_clusters}/group_parcellation.nii.gz")
    print(f"  Uploading to s3://{bucket}/{s3_key}")
    try:
        s3.upload_file(local_nifti, bucket, s3_key)
        print(f"  Upload complete")
    except Exception as e:
        print(f"  Upload failed: {e}")

    # Also upload the raw .npy labels this method produced
    local_npy = outfile
    if os.path.exists(local_npy):
        s3_npy_key = (f"{S3_GROUP_OUTPUT_PREFIX}/{use_set}/{group_name}/{method}"
                      f"/ROI_{num_clusters}/group_parcellation.npy")
        try:
            s3.upload_file(local_npy, bucket, s3_npy_key)
        except Exception as e:
            print(f"  Upload of {os.path.basename(local_npy)} failed: {e}")


# ── Main ──────────────────────────────────────────────────────────────────────
def main():
    args = parse_args()

    # Validate inputs
    if not os.path.exists(args.participants):
        print(f"ERROR: Participants file not found: {args.participants}")
        return
    if not os.path.exists(args.mask):
        print(f"ERROR: Mask file not found: {args.mask}")
        return
    if not os.path.exists(args.split_file):
        print(f"ERROR: Split file not found: {args.split_file}")
        if os.path.abspath(args.split_file) == DEFAULT_SPLIT_PATH:
            print("  Generate it with: python make_gsp_split.py --participants <GSP_participants.tsv>")
        return

    # Load split
    split_subjects = load_split_subjects(args.split_file, args.use_set)

    n_voxels = get_n_voxels(args.mask)
    print(f"\nMask voxels: {n_voxels}")
    print(f"Method: {args.method}")
    print(f"STAI-t split: {args.split}")
    print(f"Using set: {args.use_set}")

    # Stratify only the split subjects
    groups = load_and_stratify(args.participants, split_subjects, args.split, args.custom_threshold)

    if args.dry_run:
        print("\nDry run complete — no clustering performed.")
        return

    if not args.bucket:
        sys.exit("ERROR: no S3 bucket given. Pass --bucket or set PARCELLATION_BUCKET.")

    os.makedirs(args.work_dir, exist_ok=True)
    s3 = boto3.client("s3")

    # Process each anxiety group
    for group_name, entries in groups.items():
        print(f"\n{'='*60}")
        print(f"Processing group: {group_name} ({len(entries)} subjects, {args.use_set} set)")
        print(f"{'='*60}")

        if len(entries) < 2:
            print(f"  Skipping {group_name} — need at least 2 subjects")
            continue

        if args.method == "two-level":
            print(f"  Downloading individual labels from S3...")
            local_files = download_individual_labels(entries, s3, args.bucket, args.clusters,
                                                     args.work_dir)

            if len(local_files) < 2:
                print(f"  Not enough label files for group clustering. Skipping.")
                continue

            outfile, group_img = run_two_level(local_files, group_name, args.clusters, n_voxels,
                                               args.work_dir, seed=args.seed)

        elif args.method == "group-mean":
            print(f"  Downloading connectivity matrices from S3...")
            local_files = download_connectivity_matrices(entries, s3, args.bucket, args.clusters,
                                                         args.work_dir)

            if len(local_files) < 2:
                print(f"  Not enough connectivity files. Did you run individual parcellation with --save-connectivity?")
                continue

            outfile, group_img = run_group_mean(local_files, group_name, args.clusters, n_voxels,
                                                args.work_dir, seed=args.seed)

        # Save and upload
        save_and_upload(group_img, outfile, group_name, args.method, args.clusters,
                        args.mask, args.bucket, s3, args.use_set, args.work_dir,
                        upload=not args.no_upload)

        # Clean up downloaded files
        for f in local_files:
            if os.path.exists(f):
                os.remove(f)

    print(f"\n{'='*60}")
    print(f"Group parcellation pipeline ({args.use_set} set) complete.")


if __name__ == "__main__":
    main()
